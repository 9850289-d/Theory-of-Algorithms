# Рекурсивна реалізація алгоритму швидкого сортування (Quicksort) 
# за схемою розбиття Хоара (Hoare partition scheme) з підрахунком метрик складності.

def quicksort(a, l, r):
    """
    Основна рекурсивна функція швидкого сортування.
    
    a: масив, що сортується
    l: лівий індекс поточного підмасиву (left)
    r: правий індекс поточного підмасиву (right)
    """
    comparisons = 0       # Лічильник порівнянь елементів
    assignments = 0       # Лічильник операцій присвоювання
    recursive_calls = 1   # Лічильник рекурсивних викликів (враховуємо поточний виклик)
    
    # Базовий випадок рекурсії: якщо підмасив має більше ніж 1 елемент (l < r)
    if l < r:
        # Виконуємо розбиття підмасиву за схемою Хоара.
        # q — індекс точки розбиття, c1 та a1 — лічильники з процедури partition
        q, c1, a1 = partition(a, l, r)
        comparisons += c1
        assignments += a1
        
        # Рекурсивний виклик для лівої частини (від l до q)
        c2, a2, r2 = quicksort(a, l, q)
        # Рекурсивний виклик для правої частини (від q + 1 до r)
        c3, a3, r3 = quicksort(a, q + 1, r)
        
        # Сумуємо метрики з усіх рекурсивних гілок
        comparisons += c2 + c3
        assignments += a2 + a3
        recursive_calls += r2 + r3
        
    return comparisons, assignments, recursive_calls


def partition(a, l, r):
    """
    Допоміжна процедура розбиття (partition) за схемою Хоара.
    Переставляє елементи так, щоб елементи, менші за опорний (pivot), 
    опинилися ліворуч, а більші — праворуч.
    """
    comparisons = 0
    assignments = 0

    # Обираємо крайній лівий елемент підмасиву як опорний (pivot)
    pivot = a[l]
    assignments += 1
    
    # Ініціалізуємо вказівники за межами поточного підмасиву
    i = l - 1  # Лівий вказівник
    j = r + 1  # Правий вказівник
    assignments += 2
    
    while True:
        # Зсуваємо лівий вказівник вправо, поки не знайдемо елемент >= pivot
        i += 1
        assignments += 1
        while a[i] < pivot:
            comparisons += 1
            i += 1
            assignments += 1
        comparisons += 1  # Порівняння, яке випередило вихід із внутрішнього циклу while

        # Зсуваємо правий вказівник вліво, поки не знайдемо елемент <= pivot
        j -= 1
        assignments += 1
        while a[j] > pivot:
            comparisons += 1
            j -= 1
            assignments += 1
        comparisons += 1  # Порівняння для виходу з циклу while

        # Перевіряємо, чи перетнулися вказівники i та j
        comparisons += 1
        if i >= j:
            # Якщо вказівники перетнулися, розбиття завершено, повертаємо точку розбиття j
            return j, comparisons, assignments
        
        # Якщо вказівники не перетнулися, міняємо місцями елементи a[i] та a[j]
        a[i], a[j] = a[j], a[i]
        assignments += 3  # Обмін через кортеж виконує 3 присвоювання під капотом


# === Блок тестування алгоритму ===
my_list = [12, 23, 67, 65, 50, 70, 80, 61, 92]

print("Оригінальний список:", my_list.copy())

# Запускаємо quicksort для всього масиву (від індексу 0 до len-1)
total_comps, total_assigs, total_calls = quicksort(my_list, 0, len(my_list) - 1)

# Виведення підсумкових результатів
print("Відсортований список:", my_list)
print(f"Загальна кількість порівнянь: {total_comps}")
print(f"Загальна кількість присвоювань: {total_assigs}")
print(f"Загальна кількість рекурсивних викликів: {total_calls}")
