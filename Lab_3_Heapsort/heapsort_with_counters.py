# Пірамідальне сортування (Heapsort) з підрахунком кількості порівнянь та присвоювань

def swap(arr, i, j):
    """Допоміжна функція для обміну двох елементів масиву місцями."""
    arr[i], arr[j] = arr[j], arr[i]
 
def sink(arr, i, n):
    """
    Процедура 'занурення' (sift-down). 
    Опускає елемент вниз по дереву, щоб відновити властивість максимальної купи (max-heap),
    де кожен батьківський вузол має бути більшим за свої дочірні.
    
    arr: масив елементів
    i: індекс поточного батьківського вузла, який занурюється
    n: поточний розмір купи (може бути меншим за довжину масиву на 2-й фазі)
    """
    comparisons = 0
    assignments = 0
    k = i
    assignments += 1
 
    while True:
        j = 2 * k + 1  # Обчислюємо індекс лівого дочірнього вузла
        assignments += 1
 
        comparisons += 1
        if j >= n:
            break  # Якщо лівого нащадка не існує (вийшли за межі купи), занурення завершено
 
        comparisons += 2
        # Перевіряємо, чи існує правий нащадок (j + 1 < n) і чи більший він за лівого (arr[j + 1] > arr[j]).
        # Якщо так, обираємо правого нащадка (збільшуємо j на 1) для порівняння з батьком.
        if j + 1 < n and arr[j + 1] > arr[j]:
            j += 1
            assignments += 1
 
        comparisons += 1
        # Якщо батьківський вузол (k) вже більший або дорівнює найбільшому нащадку (j),
        # властивість купи дотримана, перериваємо цикл.
        if arr[k] >= arr[j]:
            break
 
        # Інакше міняємо батька з найбільшим нащадком місцями
        swap(arr, k, j)
        assignments += 3  # Під капотом swap() робить 3 присвоювання
        k = j             # Спускаємось на рівень нижче для наступної ітерації
        assignments += 1
 
    return comparisons, assignments
 
def heapsort(arr):
    """
    Основна функція сортування купою.
    Повертає відсортований масив, загальну кількість порівнянь та присвоювань.
    """
    n = len(arr)
    total_comparisons = 0
    total_assignments = 0
 
    print(f"Початковий масив: {arr}\n")
    print("--- Фаза 1: Побудова максимальної купи ---")
 
    # Починаємо з останнього батьківського вузла (n // 2 - 1) і йдемо до кореня (0).
    # Після завершення цього циклу найбільший елемент опиниться в arr[0].
    for i in range((n // 2) - 1, -1, -1):
        print(f"Занурюємо елемент з індексу {i}: {arr[i]}")
        c, a = sink(arr, i, n)
        total_comparisons += c
        total_assignments += a
 
    print(f"\nМасив після побудови купи: {arr}\n")
    print("--- Фаза 2: Сортування ---")
 
    # На кожній ітерації беремо максимальний елемент (з кореня, arr[0]) 
    # і ставимо його в кінець невідсортованої частини масиву (arr[i]).
    for i in range(n - 1, 0, -1):
        print(f"Міняємо місцями корінь ({arr[0]}) та останній елемент ({arr[i]})")
        swap(arr, 0, i)
        total_assignments += 3
 
        n_current = i  # Розмір купи зменшується на 1 (останній елемент вже відсортований)
        print(f"Розмір купи зменшився до {n_current}. Відновлюємо властивості купи.")
        
        # Після обміну новий корінь зазвичай порушує властивість купи, тому "занурюємо" його
        c, a = sink(arr, 0, n_current)
        total_comparisons += c
        total_assignments += a
        print(f"Масив на поточному кроці: {arr}\n")
 
    return arr, total_comparisons, total_assignments
 
# === Блок виконання (тестування) ===
my_list = [12, 23, 67, 65, 50, 70, 80, 61, 92]

# Викликаємо сортування, передаючи копію списку (.copy()), щоб не змінити оригінальний
sorted_list, comps, assigs = heapsort(my_list.copy())

# Виведення підсумкових результатів
print(f"Відсортований масив: {sorted_list}")
print(f"Загальна кількість порівнянь: {comps}")
print(f"Загальна кількість присвоювань: {assigs}")
